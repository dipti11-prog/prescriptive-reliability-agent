"""report.py - render a Prescription as an engineer-ready Markdown report."""
from __future__ import annotations


def _fmt_days(d):
    return "-" if d is None else ("now" if d == 0 else f"{d:.1f}")


def to_markdown(p) -> str:
    a = p.asset
    if p.status == "healthy":
        return f"# {a['tag']} {a['name']} - Reliability Assessment\n\n**Status: healthy.** {p.summary}\n"
    d = p.diagnosis
    out = [f"# {a['tag']} {a['name']} - Prescriptive Reliability Assessment", "",
           f"*Analysis time: {p.analysis_time} | First alert: {p.alert_time} | "
           f"Criticality {a['criticality']} | Status: **{p.approval}***", "",
           "## Summary", "", p.summary, "",
           "## 1. Diagnosis", "",
           f"**{d['name']}** - {d['component']}  ",
           f"ISO 14224 failure mode: {d['iso14224_failure_mode']} | Mechanism: {d['mechanism']} | "
           f"Severity {d['severity']}/10 | Typical P-F interval {d['pf_interval_days']} days", "",
           "| Rank | Failure mode | Match | Likelihood | Unexplained symptoms |", "|---|---|---|---|---|"]
    for i, h in enumerate(p.hypotheses[:5], 1):
        out.append(f"| {i} | {h['fm_id']} {h['name']} | {h['match_score']:.0%} | {h['likelihood']:.0%} | "
                   f"{', '.join(h['unexplained']) or '-'} |")
    out += ["", "**Evidence for the leading hypothesis**", "",
            "| Symptom | Expected | Observed (sigma) | Weight | Verdict |", "|---|---|---|---|---|"]
    for e in d["evidence"]:
        out.append(f"| {e['label']} | {e['expected']} | {e['z']:+.1f} | {e['weight']} | {e['verdict']} |")
    out += ["", "**Likely causes:** " + "; ".join(d["likely_causes"]), ""]
    if p.ambiguous:
        out += ["> **Diagnosis not conclusive.** Run these checks to separate the look-alikes:", ""]
        out += [f"> - {c}" for c in p.discriminating_checks] + [""]

    out += ["## 2. Time to act", "",
            "| Sensor | Normal | Now | Alarm | Trip | Days to alarm | Days to trip |", "|---|---|---|---|---|---|---|"]
    for f in p.forecast:
        out.append(f"| {f['label']} ({f['unit']}) | {f['normal']} | {f['now']} | {f['alarm']} | {f['trip']} | "
                   f"{_fmt_days(f['days_to_alarm'])} | {_fmt_days(f['days_to_trip'])} |")
    pr = p.priority
    out += ["", f"**Priority P{pr['level']} - {pr['label']}: {pr['window']}.**  ",
            f"Rule inputs: {pr['rule_inputs']}", ""]

    out += ["## 3. Recommended actions", ""]
    titles = {"confirm": "Confirm the diagnosis", "immediate": "Immediate (protect the machine)",
              "corrective": "Corrective (fix the defect)", "defect_elimination": "Defect elimination (stop it coming back)"}
    for k, t in titles.items():
        out.append(f"**{t}**")
        out += [f"- {x}" for x in p.actions[k]] + [""]

    h = p.history
    out += ["## 4. Maintenance history", "",
            f"{h['count']} event(s) of this failure mode on {a['tag']} in the last 36 months "
            f"({h['coded']} coded, {h['found_by_text_only']} found only by text search). "
            + ("**Bad actor - RCA recommended.**" if h["bad_actor"] else ""), "",
            "| WO | Date | Equipment | Text | Similarity |", "|---|---|---|---|---|"]
    for w in p.similar_work_orders:
        out.append(f"| {w['wo_id']} | {w['date']} | {w['equipment']} | {w['short_text']} - {w['long_text'][:90]}... | {w['similarity']:.2f} |")

    e = p.economics
    out += ["", "## 5. Value of acting now (illustrative)", "",
            f"- Run-to-failure: ~USD {e['unplanned_cost_usd']:,.0f}",
            f"- Planned intervention: ~USD {e['planned_cost_usd']:,.0f}",
            f"- **Avoided cost: ~USD {e['value_of_acting_now_usd']:,.0f}**",
            f"- Basis: {e['basis']}", ""]

    n = p.notification
    out += ["## 6. Draft CMMS notification", "", "| Field | Value |", "|---|---|"]
    out += [f"| {k.replace('_', ' ').title()} | {v} |" for k, v in n.items()]

    out += ["", "## 7. Agent reasoning trace", "", "| Step | Tool | Result |", "|---|---|---|"]
    out += [f"| {t['step']} | `{t['tool']}` | {t['result']} |" for t in p.trace]
    out += ["", "---", "*Generated by the Prescriptive Reliability Agent on synthetic data. "
            "Recommendations require approval by a competent engineer.*"]
    return "\n".join(out)
